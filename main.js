let canvas, ctx, animationFrameId;
let particles = [];
let mouse = { x: null, y: null, radius: 150 };
let isRunning = false;
let isCanvasVisible = true;

function initCanvasBackground() {
    canvas = document.getElementById('abyss-canvas');
    if (!canvas) return;
    ctx = canvas.getContext('2d');

    resizeCanvas();
    window.addEventListener('resize', resizeCanvas);
    
    window.addEventListener('mousemove', (e) => {
        mouse.x = e.clientX;
        mouse.y = e.clientY;
    });

    window.addEventListener('mouseleave', () => {
        mouse.x = null;
        mouse.y = null;
    });

    // Page visibility check to pause rendering
    document.addEventListener('visibilitychange', () => {
        if (document.hidden) {
            stopCanvasLoop();
        } else {
            startCanvasLoop();
        }
    });

    // Scroll Observer to pause canvas outside view
    const observer = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            isCanvasVisible = entry.isIntersecting;
            if (isCanvasVisible) {
                startCanvasLoop();
            } else {
                stopCanvasLoop();
            }
        });
    }, { threshold: 0.05 });
    observer.observe(canvas);

    createParticles();
    startCanvasLoop();
}

function resizeCanvas() {
    if (!canvas) return;
    canvas.width = window.innerWidth;
    canvas.height = window.innerHeight;
    createParticles();
}

class Particle {
    constructor(x, y) {
        this.x = x;
        this.y = y;
        this.baseX = x;
        this.baseY = y;
        this.size = Math.random() * 2 + 1;
        this.speedX = (Math.random() - 0.5) * 0.4;
        this.speedY = (Math.random() - 0.5) * 0.4;
        this.density = (Math.random() * 30) + 10;
        this.colorAlpha = Math.random() * 0.5 + 0.3;
    }

    draw() {
        ctx.beginPath();
        if (activeTheme === 'dark') {
            ctx.arc(this.x, this.y, this.size, 0, Math.PI * 2);
            ctx.fillStyle = `rgba(0, 242, 254, ${this.colorAlpha})`;
            ctx.shadowBlur = 8;
            ctx.shadowColor = '#00f2fe';
        } else {
            // Light theme: rising dandelion seeds/fluff
            ctx.arc(this.x, this.y, this.size * 2, 0, Math.PI * 2);
            ctx.fillStyle = `rgba(102, 126, 234, ${this.colorAlpha * 0.4})`;
            ctx.shadowBlur = 0;
        }
        ctx.fill();
    }

    update() {
        // Slow float
        if (activeTheme === 'dark') {
            this.x += this.speedX;
            this.y += this.speedY;

            // Bounce on boundary
            if (this.x < 0 || this.x > canvas.width) this.speedX *= -1;
            if (this.y < 0 || this.y > canvas.height) this.speedY *= -1;
            
            // Mouse repulsion physics
            if (mouse.x != null && mouse.y != null) {
                let dx = mouse.x - this.x;
                let dy = mouse.y - this.y;
                let distance = Math.hypot(dx, dy);
                if (distance < mouse.radius) {
                    let forceDirectionX = dx / distance;
                    let forceDirectionY = dy / distance;
                    let force = (mouse.radius - distance) / mouse.radius;
                    let directionX = forceDirectionX * force * this.density * 0.5;
                    let directionY = forceDirectionY * force * this.density * 0.5;
                    this.x -= directionX;
                    this.y -= directionY;
                }
            }
        } else {
            // Light mode: float up and drift gently right
            this.y -= Math.abs(this.speedY) * 0.8 + 0.2;
            this.x += this.speedX * 0.5 + 0.1;
            
            if (this.y < -10) {
                this.y = canvas.height + 10;
                this.x = Math.random() * canvas.width;
            }
            if (this.x > canvas.width + 10) {
                this.x = -10;
            }
        }
    }
}

function createParticles() {
    particles = [];
    // Adjust density based on screen width
    const particleCount = Math.floor((window.innerWidth * window.innerHeight) / 18000);
    const count = Math.min(Math.max(particleCount, 25), 80);
    
    for (let i = 0; i < count; i++) {
        let x = Math.random() * canvas.width;
        let y = Math.random() * canvas.height;
        particles.push(new Particle(x, y));
    }
}

function resetCanvasParticles() {
    createParticles();
}

function connectNodes() {
    if (activeTheme !== 'dark') return; // Only connect nodes in dark mode
    let maxDistance = 140;
    for (let a = 0; a < particles.length; a++) {
        for (let b = a; b < particles.length; b++) {
            let dx = particles[a].x - particles[b].x;
            let dy = particles[a].y - particles[b].y;
            let distance = Math.hypot(dx, dy);

            if (distance < maxDistance) {
                let alpha = (1 - (distance / maxDistance)) * 0.15;
                ctx.strokeStyle = `rgba(0, 242, 254, ${alpha})`;
                ctx.lineWidth = 1;
                ctx.shadowBlur = 0; // Disable shadow glow for line drawing (prevents lag)
                ctx.beginPath();
                ctx.moveTo(particles[a].x, particles[a].y);
                ctx.lineTo(particles[b].x, particles[b].y);
                ctx.stroke();
            }
        }
    }
}

function animate() {
    if (!isRunning) return;
    ctx.clearRect(0, 0, canvas.width, canvas.height);
    
    // Draw background grid helper
    particles.forEach(p => {
        p.update();
        p.draw();
    });
    connectNodes();
    animationFrameId = requestAnimationFrame(animate);
}

function startCanvasLoop() {
    if (!isRunning && isCanvasVisible && !document.hidden) {
        isRunning = true;
        animate();
    }
}

function stopCanvasLoop() {
    isRunning = false;
    if (animationFrameId) {
        cancelAnimationFrame(animationFrameId);
    }
}

