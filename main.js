// 🌓 THEME ENGINE
// ============================================================================
function initTheme() {
    const savedTheme = localStorage.getItem('furyfishTheme') || 'dark';
    setTheme(savedTheme);

    const toggleBtn = document.getElementById('theme-toggle');
    if (toggleBtn) {
        toggleBtn.addEventListener('click', () => {
            const newTheme = activeTheme === 'dark' ? 'light' : 'dark';
            setTheme(newTheme);
        });
    }
}

function setTheme(theme) {
    activeTheme = theme;
    localStorage.setItem('furyfishTheme', theme);
    document.documentElement.setAttribute('data-theme', theme);
    
    // Update active theme switch visual state
    const toggleIconMoon = document.querySelector('.theme-toggle-icon:nth-child(2)');
    const toggleIconSun = document.querySelector('.theme-toggle-icon:nth-child(3)');
    if (toggleIconMoon && toggleIconSun) {
        if (theme === 'dark') {
            toggleIconMoon.style.opacity = '1';
            toggleIconSun.style.opacity = '0.5';
        } else {
            toggleIconMoon.style.opacity = '0.5';
            toggleIconSun.style.opacity = '1';
        }
    }
    
    // Reset canvas if running
    if (typeof resetCanvasParticles === 'function') {
        resetCanvasParticles();
    }
}

// ============================================================================
// 🌍 MULTI-LANGUAGE SYSTEM
// ============================================================================
function initLanguage() {
    currentLang = localStorage.getItem('furyfishLang') || 'en';
    updateLanguageDOM(currentLang);

    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.addEventListener('click', () => {
            const lang = btn.dataset.lang;
            localStorage.setItem('furyfishLang', lang);
            updateLanguageDOM(lang);
            // Re-render dynamic elements
            if (loadedGamesCache.length > 0) {
                renderGamesInGrid(loadedGamesCache);
            }
        });
    });
}

function updateLanguageDOM(lang) {
    currentLang = lang;
    const t = translations[lang] || translations['en'];

    // Update keys dynamically
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (t && t[key]) {
            if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                el.placeholder = t[key];
            } else {
                el.innerHTML = t[key];
            }
        }
    });

    // Language buttons active state
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.toggle('active', btn.dataset.lang === lang);
    });
}

