function setupShowcaseInteractions() {
    const cards = document.querySelectorAll('.project-card');
    
    cards.forEach(card => {
        // Remove existing listeners to avoid doubling
        card.replaceWith(card.cloneNode(true));
    });

    // Re-query elements
    const updatedCards = document.querySelectorAll('.project-card');
    updatedCards.forEach(card => {
        // Tilt animation
        card.addEventListener('mousemove', (e) => {
            const rect = card.getBoundingClientRect();
            const x = e.clientX - rect.left;
            const y = e.clientY - rect.top;
            
            const centerX = rect.width / 2;
            const centerY = rect.height / 2;
            
            const rotateX = -(y - centerY) / centerY * 8; // Max 8 degrees
            const rotateY = (x - centerX) / centerX * 8;
            
            card.style.transform = `rotateX(${rotateX}deg) rotateY(${rotateY}deg) scale(1.02)`;
        });

        card.addEventListener('mouseleave', () => {
            card.style.transform = 'rotateX(0deg) rotateY(0deg) scale(1)';
        });

        // Click event to open Case Study modal
        card.addEventListener('click', () => {
            const projectId = card.getAttribute('data-project-id');
            openProjectModal(projectId);
        });
    });

    // Run filter immediately to maintain active tab visual bounds
    applyGridFilter(activeFilter);
}

